"""Bundle local modules into one REFramework autorun file without runtime require."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
parts=['-- Generated by tools/build_explore_lua.py; edit lua/explore and lua/model sources.\n']
for name,symbol in [('explore/core','Core'),('explore/journal','Journal'),('explore/trace','Trace'),
                    ('model/visibility','Visibility'),('model/ethan','Ethan'),('model/session','HeadSession')]:
 parts.append(f'local {symbol}=(function()\n'+(root/f'lua/{name}.lua').read_text()+'\nend)()\n')
parts.append((root/'lua/explore/adapter.lua').read_text())
(root/'build').mkdir(exist_ok=True)
(root/'build/re7_ots_explore.lua').write_text('\n'.join(parts))

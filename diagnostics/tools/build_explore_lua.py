"""Bundle local modules into one REFramework autorun file without runtime require."""
from pathlib import Path


def render(root):
    parts=['-- Generated by tools/build_explore_lua.py; edit lua/explore and lua/model sources.\n']
    for name,symbol in [('explore/transport','Transport'),('explore/core','Core'),('explore/journal','Journal'),('explore/trace','Trace'),
                        ('model/visibility','Visibility'),('model/ethan','Ethan'),('model/session','HeadSession'),
                        ('model/group','ModelGroup'),('explore/physics','Physics'),('explore/obstacle','Obstacle'),
                        ('explore/probe','Probe'),('explore/prompt','Prompt')]:
        parts.append(f'local {symbol}=(function()\n'+(root/f'lua/{name}.lua').read_text(encoding='utf-8')+'\nend)()\n')
    parts.append((root/'lua/explore/adapter.lua').read_text(encoding='utf-8'))
    return '\n'.join(parts)


if __name__ == '__main__':
    root=Path(__file__).resolve().parents[1]
    (root/'build').mkdir(exist_ok=True)
    (root/'build/re7_ots_explore.lua').write_bytes(render(root).encode('utf-8'))
